export interface NHLTeam {
  id: string;
  name: string;
  franchise: string;
  city: string;
  state: string;
  stateName: string;
  arena: string;
  stadium: string; // Alias for arena for backwards compatibility
  conference: Conference;
  division: FullDivision;
  established: number;
  championships: number; // Stanley Cups
  stanleyCups: number;
  superBowls: number; // Backwards compatibility alias
  primaryColor: string;
  secondaryColor: string;
  textColor: string;
  coordinates: { x: number; y: number };
  funFact: string;
  logoUrl: string;
  websiteUrl?: string;
}

// Backwards-compatible type aliases
export type NBATeam = NHLTeam;
