export type Conference = 'AL' | 'NL';
export type DivisionName = 'East' | 'Central' | 'West';
export type FullDivision = `${Conference} ${DivisionName}`;
export type StateConferenceAffiliation = 'AL' | 'NL' | 'Both' | 'None';

export interface MLBTeam {
  id: string;
  name: string;
  franchise: string;
  city: string;
  state: string;
  stateName: string;
  ballpark: string;
  arena: string; // Alias for ballpark for compatibility
  stadium: string; // Alias for ballpark for compatibility
  conference: Conference; // American League (AL) or National League (NL)
  league: Conference;
  division: FullDivision;
  established: number;
  championships: number; // World Series titles
  worldSeries: number;
  superBowls: number; // Backwards compatibility alias
  primaryColor: string;
  secondaryColor: string;
  textColor: string;
  coordinates: { x: number; y: number };
  funFact: string;
  logoUrl: string;
  websiteUrl?: string;
}

// Backwards-compatible type aliases
export type NBATeam = MLBTeam;
export type NFLTeam = MLBTeam;

